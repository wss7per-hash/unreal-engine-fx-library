DEFAULT_LANG = "zh"


def detect_language():
    try:
        loc = locale.getdefaultlocale()[0]
        if loc and loc.startswith("zh"):
            return "zh"
    except Exception:
        pass
    return "en"


def current_language():
    try:
        cfg_data = cfg.load()
    except Exception:
        cfg_data = {}
    lang = cfg_data.get("language", "auto")
    if lang in TRANSLATIONS:
        return lang
    return detect_language()


_cached_lang = None


def tr(key, **kwargs):
    global _cached_lang
    if _cached_lang is None:
        _cached_lang = current_language()
    lang = _cached_lang
    text = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG]).get(key, key)
    return text.format(**kwargs) if kwargs else text


def reset_language_cache():
    global _cached_lang
    _cached_lang = None
